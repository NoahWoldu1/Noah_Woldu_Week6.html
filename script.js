// Variables and Data Types
let myName = "Noah";
let myAge = 19;
let likesJavaScript = true;

// Display the string variable using alert()
alert(myName);

// Display all three variables using console.log()
console.log(myName);
console.log(myAge);
console.log(likesJavaScript);


// Basic Operations
let agePlusFive = myAge + 5;
let ageMinusTwo = myAge - 2;

// Display the results using console.log()
console.log(agePlusFive);
console.log(ageMinusTwo);


